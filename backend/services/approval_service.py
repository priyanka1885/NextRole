"""
Approval service (FR-008, FR-027, FR-060, ERR-007/008) and PDF export
(FR-007, FR-044, FR-067/068).
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Dict

from backend.db import database as db
from backend.models.schemas import ApprovalStatusEnum, TailoredResume
from backend.pipeline.graph import get_compiled_graph, thread_config
from backend.rendering.rendercv_adapter import RenderError, render_tailored_resume_pdf
from backend.services.errors import ApprovalError, SessionNotFoundError
from backend.services.pipeline_service import persist_run_outputs


def _load_pending_tailored_resume(session_id: str) -> TailoredResume:
    doc = db.get_latest_document(session_id, "tailored_resume")
    if not doc:
        raise ApprovalError("No tailored resume is available for this session yet.")
    return TailoredResume.model_validate(doc["content"])


def _resume_graph_after_decision(session_id: str, decision: ApprovalStatusEnum) -> Dict[str, Any]:
    graph = get_compiled_graph()
    config = thread_config(session_id)

    snapshot = graph.get_state(config)
    if not snapshot or not snapshot.values.get("tailored_resume"):
        raise ApprovalError(
            "Pipeline is not currently paused at the approval gate for this session."
        )

    tailored: TailoredResume = snapshot.values["tailored_resume"]
    tailored.approval_status = decision

    graph.update_state(config, {"tailored_resume": tailored, "approval_status": decision})
    result_state = graph.invoke(None, config=config)
    persist_run_outputs(session_id, result_state)
    return result_state


def approve_resume(session_id: str) -> ApprovalStatusEnum:
    """FR-008/FR-060: approve the pending tailored resume, unblocking export
    and resuming the pipeline into the Interview Coach stage."""
    if not db.session_exists(session_id):
        raise SessionNotFoundError(f"No session found for id '{session_id}'.")

    tailored = _load_pending_tailored_resume(session_id)
    if tailored.flagged_items:
        # ERR-008: fabrication guardrail flags block export until acknowledged.
        # Approval itself is still allowed (so the user can see/acknowledge the
        # flags in the UI), but the flags remain visible on the document and
        # export re-checks them (see export_resume_pdf).
        pass

    _resume_graph_after_decision(session_id, ApprovalStatusEnum.APPROVED)

    doc = db.get_latest_document(session_id, "tailored_resume")
    db.save_approval(doc["id"], ApprovalStatusEnum.APPROVED.value)
    return ApprovalStatusEnum.APPROVED


def reject_resume(session_id: str) -> ApprovalStatusEnum:
    """FR-060/ERR-007: request changes; resume returns to editable/pending
    state (regenerated by the Resume Agent) and export stays disabled."""
    if not db.session_exists(session_id):
        raise SessionNotFoundError(f"No session found for id '{session_id}'.")

    _load_pending_tailored_resume(session_id)
    _resume_graph_after_decision(session_id, ApprovalStatusEnum.CHANGES_REQUESTED)

    doc = db.get_latest_document(session_id, "tailored_resume")
    db.save_approval(doc["id"], ApprovalStatusEnum.CHANGES_REQUESTED.value)
    return ApprovalStatusEnum.CHANGES_REQUESTED


def export_resume_pdf(session_id: str) -> Path:
    """FR-007/FR-044: export the approved tailored resume as a PDF.

    Raises ApprovalError if the resume is not approved (ERR-007) or if
    unacknowledged fabrication flags are present (ERR-008); raises
    backend.rendering.rendercv_adapter.RenderError if rendering fails
    (FR-068).
    """
    if not db.session_exists(session_id):
        raise SessionNotFoundError(f"No session found for id '{session_id}'.")

    doc = db.get_latest_document(session_id, "tailored_resume")
    if not doc:
        raise ApprovalError("No tailored resume is available for this session yet.")

    tailored = TailoredResume.model_validate(doc["content"])
    if tailored.approval_status != ApprovalStatusEnum.APPROVED:
        raise ApprovalError("The tailored resume must be approved before it can be exported.")
    if tailored.flagged_items:
        raise ApprovalError(
            "Export is blocked: unacknowledged guardrail flags on the tailored "
            f"resume ({len(tailored.flagged_items)} item(s)). Resolve or "
            "acknowledge the flagged content before exporting."
        )

    resume_row = db.get_resume(session_id)
    if not resume_row:
        raise ApprovalError("No source resume found for this session.")

    try:
        return render_tailored_resume_pdf(tailored, resume_row["raw_text"], session_id)
    except RenderError:
        raise
